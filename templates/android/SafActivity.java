    private static String treeToPath(Uri tree) {
        try {
            String documentId = DocumentsContract.getTreeDocumentId(tree);
            if (documentId == null) return null;
            int colon = documentId.indexOf(':');
            if (colon < 0) return null;
            if (!"primary".equalsIgnoreCase(documentId.substring(0, colon))) return null;
            String relative = documentId.substring(colon + 1);
            File base = Environment.getExternalStorageDirectory();
            return relative.isEmpty() ? base.getAbsolutePath() : new File(base, relative).getAbsolutePath();
        } catch (Exception e) {
            return null;
        }
    }

    @Override
    protected void onActivityResult(int requestCode, int resultCode, Intent data) {
        super.onActivityResult(requestCode, resultCode, data);
        if (requestCode != REQ_OPEN && requestCode != REQ_SAVE && requestCode != REQ_FOLDER) return;
        Long boxedId = requestIds.remove(requestCode);
        if (boxedId == null) return;
        final long id = boxedId;
        final String kind = requestCode == REQ_OPEN ? "open" : requestCode == REQ_SAVE ? "save" : "folder";
        if (resultCode != RESULT_OK || data == null) {
            suggestedNames.remove(id);
            requestExtensions.remove(id);
            enqueueCancel(id, kind);
            return;
        }
        if (requestCode == REQ_FOLDER) {
            Uri tree = data.getData();
            String path = tree == null ? null : treeToPath(tree);
            if (path == null) {
                enqueueError(id, kind, "Only folders on the device's main storage can be opened");
                return;
            }
            persistPermission(tree, data);
            try {
                JSONArray paths = new JSONArray();
                paths.put(path);
                JSONObject result = base(id, kind, "ok");
                result.put("paths", paths);
                results.offer(result.toString());
            } catch (Exception e) {
                enqueueError(id, kind, e.toString());
            }
            return;
        }
        if (requestCode == REQ_SAVE) {
            Uri uri = data.getData();
            if (uri == null) { enqueueCancel(id, kind); return; }
            persistPermission(uri, data);
            try {
                String name = displayName(uri);
                if (name == null || name.trim().isEmpty()) name = suggestedNames.getOrDefault(id, "untitled");
                // DocumentsUI lets the user shorten the name to one without an extension even though
                // the app asked to save `Book.xlsx`. The app then appends an extension of its own and
                // writes `Book.xlsx` while the staged copy watched for the commit is `Book` — the
                // chosen document stayed 0 B. Keep the extension the app asked to save as, so the
                // staged path is the path the app writes.
                name = keepSuggestedExtension(name, suggestedNames.get(id));
                File stage = newStageFile(name, uri);
                rememberUri(stage, uri);
                enqueueSave(id, stage.getAbsolutePath());
            } catch (Exception e) {
                enqueueError(id, kind, e.toString());
            } finally {
                suggestedNames.remove(id);
            }
            return;
        }

        List<Uri> uris = new ArrayList<>();
        ClipData clip = data.getClipData();
        if (clip != null) {
            for (int i = 0; i < clip.getItemCount(); i++) {
                Uri uri = clip.getItemAt(i).getUri();
                if (uri != null) uris.add(uri);
            }
        } else if (data.getData() != null) {
            uris.add(data.getData());
        }
        if (uris.isEmpty()) { requestExtensions.remove(id); enqueueCancel(id, kind); return; }
        final List<String> allowedExts = requestExtensions.remove(id);
        if (allowedExts != null && !allowedExts.isEmpty()) {
            for (Uri uri : uris) {
                String name = displayName(uri);
                String ext = getFileExtension(name);
                if (!allowedExts.contains(ext)) {
                    enqueueError(id, "open", "Selected file '" + name + "' is not a supported format (" + String.join(", ", allowedExts) + ")");
                    return;
                }
            }
        }
        for (Uri uri : uris) persistPermission(uri, data);
        io.execute(() -> {
            try {
                JSONArray paths = new JSONArray();
                for (Uri uri : uris) {
                    File stage = newStageFile(displayName(uri), uri);
                    copyUriToFile(uri, stage);
                    rememberUri(stage, uri);
                    paths.put(stage.getAbsolutePath());
                }
                JSONObject result = base(id, "open", "ok");
                result.put("paths", paths);
                results.offer(result.toString());
            } catch (Exception e) {
                enqueueError(id, "open", e.toString());
            }
        });
    }

    /**
     * Commit an app-private staged file to its remembered SAF URI; used by Rust after every save.
     *
     * <p>The app may write a sibling of the staged path it was handed — GridCraft appends or
     * replaces the extension after the picker returns, so "Book" becomes "Book.xlsx". The exact
     * path has no mapping then; fall back to the staged path in the same folder with the same
     * stem, which is what the user actually chose.
     */
    public String safCommit(String path) {
        try {
            String uriText = getSharedPreferences(PREFS, MODE_PRIVATE).getString("uri:" + path, null);
            if (uriText == null) uriText = uriForSibling(path);
            if (uriText == null) return "NONE";
            Uri uri = Uri.parse(uriText);
            OutputStream out = getContentResolver().openOutputStream(uri, "wt");
            if (out == null) out = getContentResolver().openOutputStream(uri, "w");
            if (out == null) return "ERROR: Android document provider did not open an output stream";
            try (InputStream in = new FileInputStream(new File(path)); OutputStream target = out) {
                byte[] buffer = new byte[64 * 1024];
                int count;
                while ((count = in.read(buffer)) != -1) target.write(buffer, 0, count);
                target.flush();
            }
            return "OK";
        } catch (Exception e) {
            Log.e(TAG, "Could not write a selected document", e);
            return "ERROR: Could not write the selected document: " + e.getMessage();
        }
    }

    /** The staged path's stem, ignoring any extension: {@code …/media/Book.xlsx} → {@code …/media/Book}. */
    private static String stagedStem(String path) {
        File file = new File(path);
        String name = file.getName();
        int dot = name.lastIndexOf('.');
        String stem = dot > 0 ? name.substring(0, dot) : name;
        File parent = file.getParentFile();
        return parent == null ? stem : new File(parent, stem).getAbsolutePath();
    }

    /** The remembered URI of a staged path whose extension the app rewrote, if there is one. */
    private String uriForSibling(String path) {
        String stem = stagedStem(path);
        try {
            for (Map.Entry<String, ?> entry : getSharedPreferences(PREFS, MODE_PRIVATE).getAll().entrySet()) {
                if (!entry.getKey().startsWith("uri:") || !(entry.getValue() instanceof String uriText)) continue;
                String staged = entry.getKey().substring("uri:".length());
                if (stagedStem(staged).equals(stem)) return uriText;
            }
        } catch (Exception e) {
            Log.w(TAG, "Could not look up a staged document", e);
        }
        return null;
    }

    /**
     * Give a name the user shortened back the extension the app asked to save as. Android's save
     * dialog lets a name be saved with no extension; the app then adds its own (say ".xlsx") and
     * writes a different staged file than the one watched for the commit, leaving the document the
     * user chose empty.
     */
    private static String keepSuggestedExtension(String name, String suggested) {
        if (name == null || suggested == null) return name;
        int dot = name.lastIndexOf('.');
        int slash = Math.max(name.lastIndexOf('/'), name.lastIndexOf('\\'));
        if (dot > slash + 1 && dot < name.length() - 1) return name;
        int suggestedDot = suggested.lastIndexOf('.');
        if (suggestedDot <= 0 || suggestedDot >= suggested.length() - 1) return name;
        return name + suggested.substring(suggestedDot);
    }

    /**
     * The working copy of a document the user chose through SAF. It is created under
     * {@link #appStorageDir()} rather than internal storage so the file the app actually edits is the
     * one a file manager or a computer finds under {@code Android/data/<pkg>/files}, and inside a
     * plain {@code media} directory named after the document instead of a random per-open directory,
     * so the same document always lands on the same path.
     *
     * <p>A document that is opened again reuses its staged file. A different document whose name is
     * already taken gets a {@code " (2)"}-style suffix, because the staged path is also the key that
     * maps back to the document the user picked: two documents sharing one path would overwrite each
     * other on save. A name whose staged copy has since been deleted (the app prunes working copies
     * the recent list let go of) is free again: the stale {@code uri:} mapping is harmless, and
     * keeping the path rather than suffixing it is what lets a cleared document come back clean.
     */
    private File newStageFile(String name, Uri uri) throws Exception {
        File dir = new File(appStorageDir(), "media");
        if (!dir.mkdirs() && !dir.isDirectory()) throw new Exception("Could not create the media directory");
        String safe = safeName(name == null ? "imported-file" : name);
        String stem = safe, extension = "";
        int dot = safe.lastIndexOf('.');
        if (dot > 0) { stem = safe.substring(0, dot); extension = safe.substring(dot); }
        SharedPreferences prefs = getSharedPreferences(PREFS, MODE_PRIVATE);
        String owner = uri == null ? null : uri.toString();
        for (int attempt = 1; attempt <= 10000; attempt++) {
            String candidate = attempt == 1 ? safe : stem + " (" + attempt + ")" + extension;
            File file = new File(dir, candidate);
            String mapped = prefs.getString("uri:" + file.getAbsolutePath(), null);
            if (mapped == null || mapped.equals(owner) || !file.exists()) return file;
        }
        throw new Exception("Could not find a free name for the selected document in " + dir);
    }

    private static String safeName(String name) {
        String clean = name.replace('\\', '/');
        int slash = clean.lastIndexOf('/');
        if (slash >= 0) clean = clean.substring(slash + 1);
        clean = clean.replaceAll("[^A-Za-z0-9._() -]", "_").trim();
        if (clean.isEmpty() || clean.equals(".") || clean.equals("..")) return "untitled";
        return clean;
    }

    private String displayName(Uri uri) {
        try (Cursor cursor = getContentResolver().query(uri, null, null, null, null)) {
            if (cursor != null && cursor.moveToFirst()) {
                int index = cursor.getColumnIndex(OpenableColumns.DISPLAY_NAME);
                if (index >= 0) return safeName(cursor.getString(index));
            }
        } catch (Exception ignored) { }
        String segment = uri.getLastPathSegment();
        return segment == null ? "imported-file" : safeName(segment);
    }

    private void persistPermission(Uri uri, Intent data) {
        try {
            int flags = data.getFlags() & (Intent.FLAG_GRANT_READ_URI_PERMISSION | Intent.FLAG_GRANT_WRITE_URI_PERMISSION);
            if (flags != 0) getContentResolver().takePersistableUriPermission(uri, flags);
        } catch (Exception e) {
            Log.i(TAG, "Provider did not offer a persistable grant for " + uri, e);
        }
    }

    private void rememberUri(File path, Uri uri) {
        getSharedPreferences(PREFS, MODE_PRIVATE).edit().putString("uri:" + path.getAbsolutePath(), uri.toString()).apply();
    }

    private void copyUriToFile(Uri uri, File destination) throws Exception {
        try (android.os.ParcelFileDescriptor pfd = getContentResolver().openFileDescriptor(uri, "r")) {
            if (pfd != null) {
                try (FileInputStream in = new FileInputStream(pfd.getFileDescriptor());
                     FileOutputStream out = new FileOutputStream(destination)) {
                    java.nio.channels.FileChannel inChannel = in.getChannel();
                    java.nio.channels.FileChannel outChannel = out.getChannel();
                    long size = inChannel.size();
                    long transferred = 0;
                    while (transferred < size) {
                        long count = outChannel.transferFrom(inChannel, transferred, size - transferred);
                        if (count <= 0) break;
                        transferred += count;
                    }
                    return;
                }
            }
        } catch (Exception ignored) { }
        InputStream input = getContentResolver().openInputStream(uri);
        if (input == null) throw new Exception("Android document provider did not open the selected file");
        try (InputStream in = input; FileOutputStream out = new FileOutputStream(destination)) {
            byte[] buffer = new byte[256 * 1024];
            int count;
            while ((count = in.read(buffer)) != -1) out.write(buffer, 0, count);
            out.flush();
        }
    }

    /**
     * Collect the file(s) an {@code ACTION_VIEW} / {@code ACTION_SEND} intent carries: the data URI
     * (opening a registered type), the intent's {@link ClipData} (modern shares) and the legacy
     * {@code EXTRA_STREAM} extra, de-duplicated. Anything else (in particular the launcher's MAIN
     * intent) is ignored so normal launches are untouched.
     */
    private static List<Uri> collectIncomingUris(Intent intent) {
        LinkedHashSet<Uri> uris = new LinkedHashSet<>();
        String action = intent.getAction();
        if (Intent.ACTION_VIEW.equals(action)) {
            if (intent.getData() != null) uris.add(intent.getData());
        } else if (Intent.ACTION_SEND.equals(action)) {
            Uri stream = intent.getParcelableExtra(Intent.EXTRA_STREAM);
            if (stream != null) uris.add(stream);
        } else if (Intent.ACTION_SEND_MULTIPLE.equals(action)) {
            ArrayList<Uri> streams = intent.getParcelableArrayListExtra(Intent.EXTRA_STREAM);
            if (streams != null) uris.addAll(streams);
        } else {
            return new ArrayList<>();
        }
        ClipData clip = intent.getClipData();
        if (clip != null) {
            for (int i = 0; i < clip.getItemCount(); i++) {
                Uri uri = clip.getItemAt(i).getUri();
                if (uri != null) uris.add(uri);
            }
        }
        return new ArrayList<>(uris);
    }

    /**
     * Copy every file the given intent carries into app-private staging and queue its path for the
     * Rust shell. Runs off the UI thread because the copy can be large; the shell polls
     * {@link #intentPoll()} until the path appears, so a slow copy never blocks startup.
     */
    private void handleIncomingFiles(Intent intent) {
        if (intent == null) return;
        List<Uri> uris = collectIncomingUris(intent);
        if (uris.isEmpty()) return;
        for (Uri uri : uris) persistPermission(uri, intent);
        io.execute(() -> {
            for (Uri uri : uris) {
                try {
                    File stage = newStageFile(displayName(uri), uri);
                    copyUriToFile(uri, stage);
                    rememberUri(stage, uri);
                    intentPaths.offer(stage.getAbsolutePath());
                } catch (Exception e) {
                    Log.e(TAG, "Could not open the file the system handed the app: " + uri, e);
                }
            }
        });
    }

    /** Every {@code content://} URI the drag carries (text-only drags yield nothing). */
    private List<Uri> collectDragUris(ClipData clip) {
        List<Uri> uris = new ArrayList<>();
        if (clip == null) return uris;
        for (int i = 0; i < clip.getItemCount(); i++) {
            Uri uri = clip.getItemAt(i).getUri();
            if (uri != null) uris.add(uri);
        }
        return uris;
    }

    /**
     * Best-effort persistable read grant for a dropped URI. Drag-and-drop only grants temporary
     * access, so a source that offered a persistable grant (the system file picker does) keeps
     * the copy below readable even after the drag ends; the rest are copied while the drop's
     * temporary grant still holds.
     */
    private void persistDroppedPermission(Uri uri) {
        try {
            getContentResolver().takePersistableUriPermission(uri, Intent.FLAG_GRANT_READ_URI_PERMISSION);
        } catch (Exception e) {
            Log.i(TAG, "Provider did not offer a persistable grant for " + uri, e);
        }
    }

    /**
     * Copy dropped files into app-private staging and queue their paths for the Rust shell,
     * mirroring {@link #handleIncomingFiles}: the copy runs off the UI thread and the shell
     * picks each path up on a later {@link #intentPoll()}.
     */
    private void stageDroppedFiles(List<Uri> uris) {
        io.execute(() -> {
            for (Uri uri : uris) {
                try {
                    File stage = newStageFile(displayName(uri), uri);
                    copyUriToFile(uri, stage);
                    rememberUri(stage, uri);
                    intentPaths.offer(stage.getAbsolutePath());
                } catch (Exception e) {
                    Log.e(TAG, "Could not stage the dropped file: " + uri, e);
                }
            }
        });
    }

    /**
     * Listen for drags on the whole window: the decor, the content frame and every child of it
     * (the native surface and the keyboard host), so the drop is caught whichever view the
     * system considers to be under the pointer. Views that don't handle a drag pass it on, so
     * the same listener on all of them never conflicts.
     */
    private void installDropTarget() {
        try {
            Window window = getWindow();
            if (window == null) return;
            View decor = window.getDecorView();
            decor.setOnDragListener(dropListener);
            View content = decor.findViewById(android.R.id.content);
            if (content == null) return;
            content.setOnDragListener(dropListener);
            if (content instanceof ViewGroup) {
                ViewGroup group = (ViewGroup) content;
                for (int i = 0; i < group.getChildCount(); i++) {
                    group.getChildAt(i).setOnDragListener(dropListener);
                }
            }
        } catch (Throwable error) {
            Log.e(TAG, "Could not install the drag-and-drop target", error);
        }
    }

    /**
     * Hand a generated PDF to Android's print system (the native print spooler). The Rust shell
     * calls this over JNI and gets a synchronous answer; staging the file and opening the system
     * print dialog happen on background/main threads afterwards, so the event loop never blocks.
     * The dialog is where printer choice, paper size, duplex, color and page range live on
     * Android — apps cannot enumerate printers themselves, and this reaches every printer the
     * system knows (Wi-Fi, network, cloud), unlike a CUPS-only desktop spooler.
     */
    public String printDocument(String title, byte[] pdf) {
        if (pdf == null || pdf.length == 0) return "ERROR: there is no document to print";
        PrintManager manager = (PrintManager) getSystemService(PRINT_SERVICE);
        if (manager == null) return "ERROR: this device has no Android print service";
        final String jobName = (title == null || title.trim().isEmpty()) ? "Document" : title;
        io.execute(() -> {
            try {
                File file = File.createTempFile("artcraft-print", ".pdf", getCacheDir());
                file.deleteOnExit();
                try (FileOutputStream out = new FileOutputStream(file)) {
                    out.write(pdf);
                }
                final int pageCount = countPdfPages(file);
                runOnUiThread(() -> {
                    try {
                        manager.print(jobName, new PdfPrintAdapter(file, jobName, pageCount), null);
                    } catch (Throwable error) {
                        Log.e(TAG, "Could not open the Android print dialog", error);
                    }
                });
            } catch (Throwable error) {
                Log.e(TAG, "Could not stage the PDF for printing", error);
            }
        });
        return "OK";
    }

    /** Page count from the system's own PDF parser; feeds PrintDocumentInfo below. */
    private static int countPdfPages(File file) throws Exception {
        try (ParcelFileDescriptor fd = ParcelFileDescriptor.open(file, ParcelFileDescriptor.MODE_READ_ONLY)) {
            PdfRenderer renderer = new PdfRenderer(fd);
            try {
                return renderer.getPageCount();
            } finally {
                renderer.close();
            }
        }
    }

    /**
     * Serves a pre-generated PDF to the print spooler. Layout is fixed (the Rust side already
     * collated pages and applied the app's range/collation settings), so onLayout just reports
     * the page count; onWrite streams the whole file through. The system dialog can still
     * request a sub-range, which falls back to the full document — the app's own range settings
     * are already baked into the PDF it hands over, so this only differs when a second range is
     * picked in the dialog itself.
     */
    private static final class PdfPrintAdapter extends PrintDocumentAdapter {
        private final File file;
        private final String title;
        private final int pageCount;

        PdfPrintAdapter(File file, String title, int pageCount) {
            this.file = file;
            this.title = title;
            this.pageCount = pageCount;
        }

        @Override
        public void onLayout(PrintAttributes oldAttributes, PrintAttributes newAttributes,
                CancellationSignal cancellationSignal, LayoutResultCallback callback, Bundle extras) {
            if (cancellationSignal != null && cancellationSignal.isCanceled()) {
                callback.onLayoutCancelled();
                return;
            }
            PrintDocumentInfo info = new PrintDocumentInfo.Builder(title)
                    .setContentType(PrintDocumentInfo.CONTENT_TYPE_DOCUMENT)
                    .setPageCount(pageCount)
                    .build();
            boolean changed = newAttributes == null || !newAttributes.equals(oldAttributes);
            callback.onLayoutFinished(info, changed);
        }

        @Override
        public void onWrite(PageRange[] pages, ParcelFileDescriptor destination,
                CancellationSignal cancellationSignal, WriteResultCallback callback) {
            if (cancellationSignal != null && cancellationSignal.isCanceled()) {
                callback.onWriteCancelled();
                return;
            }
            try (FileInputStream in = new FileInputStream(file);
                    FileOutputStream out = new FileOutputStream(destination.getFileDescriptor())) {
                byte[] buffer = new byte[64 * 1024];
                int count;
                while ((count = in.read(buffer)) != -1) out.write(buffer, 0, count);
                callback.onWriteFinished(null);
            } catch (Throwable error) {
                callback.onWriteFailed(String.valueOf(error));
            }
        }
    }

    @Override
    public boolean dispatchGenericMotionEvent(MotionEvent event) {
        // Trackpad/touchpad/mouse/stylus should go through native handling (enables tap-to-click)
        if (event != null && (
            event.isFromSource(android.view.InputDevice.SOURCE_TOUCHPAD) ||
            event.isFromSource(android.view.InputDevice.SOURCE_MOUSE) ||
            event.isFromSource(android.view.InputDevice.SOURCE_STYLUS)
        )) {
            return super.dispatchGenericMotionEvent(event);
        }
        return super.dispatchGenericMotionEvent(event);
    }

    private JSONObject base(long id, String kind, String status) throws Exception {
        JSONObject value = new JSONObject();
        value.put("id", id);
        value.put("kind", kind);
        value.put("status", status);
        return value;
    }

    private void enqueueCancel(long id, String kind) {
        try { results.offer(base(id, kind, "cancel").toString()); }
        catch (Exception e) { Log.e(TAG, "Could not encode cancellation", e); }
    }

    private void enqueueError(long id, String kind, String message) {
        try {
            JSONObject value = base(id, kind, "error");
            value.put("message", message == null ? "Unknown Android file picker error" : message);
            results.offer(value.toString());
        } catch (Exception e) { Log.e(TAG, "Could not encode picker error", e); }
    }

    private void enqueueSave(long id, String path) {
        try {
            JSONObject value = base(id, "save", "ok");
            value.put("path", path);
            results.offer(value.toString());
        } catch (Exception e) { enqueueError(id, "save", e.toString()); }
    }

    private static String mimeFor(String fileName) {
        String lower = fileName.toLowerCase(java.util.Locale.ROOT);
        if (lower.endsWith(".png")) return "image/png";
        if (lower.endsWith(".jpg") || lower.endsWith(".jpeg")) return "image/jpeg";
        if (lower.endsWith(".webp")) return "image/webp";
        if (lower.endsWith(".gif")) return "image/gif";
        if (lower.endsWith(".tif") || lower.endsWith(".tiff")) return "image/tiff";
        if (lower.endsWith(".bmp")) return "image/bmp";
        if (lower.endsWith(".svg")) return "image/svg+xml";
        if (lower.endsWith(".pdf")) return "application/pdf";
        if (lower.endsWith(".txt") || lower.endsWith(".md")) return "text/plain";
        if (lower.endsWith(".json")) return "application/json";
        if (lower.endsWith(".html") || lower.endsWith(".htm")) return "text/html";
        if (lower.endsWith(".epub")) return "application/epub+zip";
        if (lower.endsWith(".zip")) return "application/zip";
        return "application/octet-stream";
    }

    private static List<String> parseExtensions(String extensionsStr) {
        List<String> list = new ArrayList<>();
        if (extensionsStr == null || extensionsStr.trim().isEmpty()) return list;
        for (String part : extensionsStr.split("[,;\\s]+")) {
            String clean = part.trim().toLowerCase(java.util.Locale.US);
            if (clean.startsWith(".")) clean = clean.substring(1);
            if (!clean.isEmpty() && !list.contains(clean)) list.add(clean);
        }
        return list;
    }

    private static List<String> resolveMimeTypes(List<String> extensions) {
        LinkedHashSet<String> mimes = new LinkedHashSet<>();
        MimeTypeMap map = MimeTypeMap.getSingleton();
        for (String ext : extensions) {
            String mime = map.getMimeTypeFromExtension(ext);
            if (mime != null) mimes.add(mime);
            switch (ext) {
                case "wasm":
                    mimes.add("application/wasm");
                    mimes.add("application/octet-stream");
                    break;
                case "psd":
                case "psb":
                    mimes.add("image/vnd.adobe.photoshop");
                    mimes.add("application/x-photoshop");
                    mimes.add("application/octet-stream");
                    break;
                case "pcraft":
                    mimes.add("application/octet-stream");
                    mimes.add("application/zip");
                    break;
                case "tif":
                case "tiff":
                    mimes.add("image/tiff");
                    break;
                case "png":
                    mimes.add("image/png");
                    break;
                case "jpg":
                case "jpeg":
                    mimes.add("image/jpeg");
                    break;
                case "webp":
                    mimes.add("image/webp");
                    break;
                case "svg":
                    mimes.add("image/svg+xml");
                    break;
                case "pdf":
                    mimes.add("application/pdf");
                    break;
                default:
                    break;
            }
        }
        return new ArrayList<>(mimes);
    }

    private static String getFileExtension(String path) {
        if (path == null) return "";
        int dot = path.lastIndexOf('.');
        return dot >= 0 ? path.substring(dot + 1).toLowerCase(java.util.Locale.US) : "";
    }
