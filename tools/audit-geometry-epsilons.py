#!/usr/bin/env python3
"""Inventory fixed numeric thresholds in CADCraft geometry Rust sources.

This is an audit aid, not an automatic rewrite: thresholds must be classified
by semantics before replacement with a drawing-aware tolerance.
"""
from __future__ import annotations
import argparse
import re
from pathlib import Path

PATTERN = re.compile(r"(?i)(?:\bEPS\b|f64::EPSILON|\b1e[-+]?\d+\b|\b\d+(?:\.\d+)?e[-+]?\d+\b)")


def classify(path: Path, line: str, in_tests: bool) -> str:
    low = line.lower()
    if in_tests or "assert!" in low or "assert_eq!" in low:
        return "test-only threshold"
    if line.lstrip().startswith(("//", "///", "*")) or low.lstrip().startswith("use crate"):
        return "documentation / symbol reference (not a threshold)"
    if any(word in low for word in ("tessell", "segments", "samples", "subdiv", "flatten")):
        return "rendering / approximation threshold"
    if any(word in low for word in ("knot", "parameter", "degree", "basis", "weight", "normaliz", "dedup", "sweep", "angle", "ratio")):
        return "parameterisation / numerical guard"
    if any(word in low for word in ("1e-300", "min_positive", "det.abs", "den.abs", "wsum", "pivot", "singular")):
        return "floating-point underflow / singularity guard"
    if any(word in low for word in ("near", "close", "intersect", "collinear", "radius", "length", "area", "dist", "epsilon", " <= eps", "< eps")):
        return "geometric decision threshold — review required"
    file_categories = {
        "curve.rs": "curve degeneracy / arc classification — review required",
        "fillet.rs": "fillet solver convergence / broad-phase threshold — review required",
        "lib.rs": "curve parameter / tessellation policy — review required",
        "mat.rs": "matrix conditioning / projection guard — review required",
        "nurbs.rs": "NURBS knot / rational evaluation guard — review required",
        "region.rs": "planar arrangement grid / parameter merge — review required",
        "spline.rs": "spline basis / rational evaluation guard — review required",
        "spline_fit.rs": "spline fitting / knot construction guard — review required",
        "tolerance.rs": "tolerance policy constant — review required",
        "vec.rs": "vector normalization threshold — review required",
    }
    return file_categories.get(path.name, "unclassified — manual disposition required")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1] / "source" / "cadcraft" / "crates" / "geom" / "src")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "GEOMETRY-FIXED-EPSILON-AUDIT.md")
    args = parser.parse_args()
    rows = []
    for path in sorted(args.root.rglob("*.rs")):
        in_tests = path.name in {"tests.rs", "property_tests.rs"}
        pending_test_module = False
        test_depth = None
        brace_depth = 0
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if "#[cfg(test)]" in line:
                pending_test_module = True
            if pending_test_module and "{" in line:
                test_depth = brace_depth + line.count("{") - line.count("}")
                pending_test_module = False
                in_tests = True
            if PATTERN.search(line):
                rows.append((path.relative_to(args.root).as_posix(), number, classify(path, line, in_tests), line.strip()))
            brace_depth += line.count("{") - line.count("}")
            if test_depth is not None and brace_depth < test_depth:
                test_depth = None
                in_tests = path.name in {"tests.rs", "property_tests.rs"}
    counts: dict[str, int] = {}
    for _, _, category, _ in rows:
        counts[category] = counts.get(category, 0) + 1
    out = ["# CADCraft geometry fixed-epsilon audit", "", "Generated by `tools/audit-geometry-epsilons.py`.", "", 
           "This inventory deliberately does not rewrite constants. A numeric threshold can be a geometric decision, a parameter-space guard, a solver convergence criterion, or a test assertion; replacing them indiscriminately would change algorithm semantics.", "", "## Summary", "", "| Classification | Occurrences |", "|---|---:|"]
    out += [f"| {name} | {count} |" for name, count in sorted(counts.items())]
    out += ["", "## Occurrences", "", "| File | Line | Classification | Source |", "|---|---:|---|---|"]
    out += [f"| `{file}` | {line} | {category} | `{source.replace('|', '&#124;')}` |" for file, line, category, source in rows]
    out += ["", "## Exit criteria", "", "- Every production occurrence has an owner and semantic classification.", "- Geometric distance decisions use a shared `ToleranceContext` or document why they cannot.", "- Parameter-space convergence thresholds are dimensionless and bounded by conditioning.", "- Underflow guards and denominator regularizers are justified independently of drawing units.", "- Test tolerances remain explicit and are not migrated as production decisions.", "- No production occurrence remains `unclassified` or `geometric decision threshold — review required` without a documented disposition.", ""]
    args.output.write_text("\n".join(out), encoding="utf-8")
    print(f"Scanned {len(list(args.root.rglob('*.rs')))} Rust files; recorded {len(rows)} threshold occurrences.")
    for name, count in sorted(counts.items()):
        print(f"{count:4d}  {name}")
    print(f"Wrote {args.output}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
